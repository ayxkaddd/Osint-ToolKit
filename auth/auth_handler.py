from datetime import datetime, timedelta, timezone
import jwt
from fastapi import HTTPException, Security
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from passlib.context import CryptContext
from telethon.errors import (
    SessionPasswordNeededError,
    PhoneNumberInvalidError,
    PhoneCodeInvalidError,
    PhoneCodeExpiredError,
    PhoneCodeEmptyError,
    PasswordHashInvalidError,
)

from utils import telegram_client
from utils.config import get_setting

TOKEN_TTL = timedelta(hours=24)


class AuthHandler:
    security = HTTPBearer()
    pwd_context = CryptContext(schemes=["bcrypt"], deprecated="auto")

    @property
    def secret(self) -> str:
        # Read at call time so a secret regenerated by /setup/admin applies without a restart
        secret = get_setting('JWT_SECRET')
        if not secret:
            raise HTTPException(status_code=503, detail='JWT_SECRET is not configured')
        return secret

    def get_password_hash(self, password):
        return self.pwd_context.hash(password)

    def verify_password(self, plain_password, hashed_password):
        if not hashed_password:
            return False
        try:
            return self.pwd_context.verify(plain_password, hashed_password)
        except ValueError:
            # Malformed hash in .env
            return False

    def encode_token(self, user_id):
        now = datetime.now(timezone.utc)
        payload = {
            'exp': now + TOKEN_TTL,
            'iat': now,
            'sub': user_id
        }
        return jwt.encode(
            payload,
            self.secret,
            algorithm='HS256'
        )

    def decode_token(self, token):
        try:
            payload = jwt.decode(token, self.secret, algorithms=['HS256'])
            return payload['sub']
        except jwt.ExpiredSignatureError:
            raise HTTPException(status_code=401, detail='Signature has expired') from None
        except (jwt.InvalidTokenError, KeyError):
            raise HTTPException(status_code=401, detail='Invalid token') from None

    def auth_wrapper(self, auth: HTTPAuthorizationCredentials = Security(security)):
        return self.decode_token(auth.credentials)


class TelegramAuthHandler:
    """Telegram login flow on the shared client (see utils.telegram_client)."""

    def __init__(self):
        self.phone_code_hash = None

    @property
    def client(self):
        return telegram_client.get_client()

    async def connect(self):
        client = await telegram_client.ensure_connected(require_authorized=False)
        return await client.is_user_authorized()

    async def send_verification_code(self, phone_number: str):
        try:
            await telegram_client.ensure_connected(require_authorized=False)
            sent_code = await self.client.send_code_request(phone_number)
            self.phone_code_hash = sent_code.phone_code_hash
            return {"status": "success", "message": "Verification code sent"}
        except PhoneNumberInvalidError:
            return {"status": "error", "message": "Invalid phone number"}
        except Exception as e:
            return {"status": "error", "message": str(e)}

    async def verify_code(self, phone_number: str, code: str):
        if not self.phone_code_hash:
            return {"status": "error", "message": "No active verification session"}

        try:
            await telegram_client.ensure_connected(require_authorized=False)
            await self.client.sign_in(
                phone=phone_number,
                code=code,
                phone_code_hash=self.phone_code_hash
            )
            return {"status": "success", "message": "Telegram authentication successful"}
        except SessionPasswordNeededError:
            return {"status": "password_required", "message": "This account has two-step verification - enter its password"}
        except (PhoneCodeInvalidError, PhoneCodeExpiredError, PhoneCodeEmptyError):
            return {"status": "error", "message": "Invalid verification code"}
        except Exception as e:
            return {"status": "error", "message": str(e)}

    async def verify_password(self, password: str):
        """Second step for accounts with two-step verification enabled."""
        try:
            await telegram_client.ensure_connected(require_authorized=False)
            await self.client.sign_in(password=password)
            return {"status": "success", "message": "Telegram authentication successful"}
        except PasswordHashInvalidError:
            return {"status": "error", "message": "Wrong two-step verification password"}
        except Exception as e:
            return {"status": "error", "message": str(e)}
